// Prepares the illustrated life-stage portraits in src/assets/loading-characters
// for the loading screen. Each portrait is trimmed and split into a "head" and a
// "body" layer (faces are left exactly as drawn) so the head can tilt gently
// while the body breathes. Stacked at rest, the two layers equal the original.
//
// Any PNG dropped into loading-characters becomes a growth stage, ordered by
// filename. The head is found automatically from facial landmarks
// (scripts/landmarks.swift); if no face is found the stage animates as one
// layer.
//
// Usage: node scripts/make-loading-characters.mjs [--preview out.png]
//   Set LANDMARKS_BIN to a compiled landmarks.swift to skip recompiling it.
import { execFileSync } from "node:child_process"
import { mkdir, readdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const inputDir = path.join(root, "src/assets/loading-characters")
const outputDir = path.join(root, "src/assets/loading-animated")

// Head mask from facial landmarks, in source pixels: head centre (cx, cy),
// chin line, half-width of the mask, and edge feather.
function findHead(file) {
    const [command, args] = process.env.LANDMARKS_BIN
        ? [process.env.LANDMARKS_BIN, [file]]
        : ["swift", [path.join(root, "scripts/landmarks.swift"), file]]
    try {
        const { points } = JSON.parse(execFileSync(command, args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }))
        const xs = points.map(([x]) => x), ys = points.map(([, y]) => y)
        const face = Math.max(...xs) - Math.min(...xs)
        return {
            cx: (Math.max(...xs) + Math.min(...xs)) / 2,
            cy: (Math.max(...ys) + Math.min(...ys)) / 2,
            chin: Math.max(...ys) + face * 0.1,
            rx: face * 1.05,
            feather: Math.max(4, face * 0.05),
        }
    } catch {
        return null
    }
}

const OUTPUT_HEIGHT = 900

async function prepare(name) {
    const { data, info } = await sharp(path.join(inputDir, `${name}.png`))
        .ensureAlpha()
        .trim({ threshold: 1 })
        .raw()
        .toBuffer({ resolveWithObject: true })
    const W = info.width
    const H = info.height
    const offsetX = -(info.trimOffsetLeft ?? 0)
    const offsetY = -(info.trimOffsetTop ?? 0)
    const toPng = (buffer) =>
        sharp(buffer, { raw: { width: W, height: H, channels: 4 } })
            .resize({ height: OUTPUT_HEIGHT })
            .png({ palette: true, quality: 92, effort: 10 })
    const head = findHead(path.join(inputDir, `${name}.png`))

    if (!head) {
        await toPng(data).toFile(path.join(outputDir, `${name}-body.png`))
        return { name, aspect: +(W / H).toFixed(4), hasHead: false, pivotX: 50, pivotY: 25 }
    }

    const cx = head.cx - offsetX
    const cy = head.cy - offsetY
    const chin = head.chin - offsetY
    const ryBottom = chin - cy
    const ryTop = ryBottom * 2.5 // reach well above the hair
    const headLayer = Buffer.from(data)
    const bodyLayer = Buffer.from(data)

    for (let y = 0; y < H; y++) {
        for (let x = 0; x < W; x++) {
            const ry = y < cy ? ryTop : ryBottom
            const e = Math.hypot((x - cx) / head.rx, (y - cy) / ry)
            const dist = (e - 1) * Math.min(head.rx, ry)
            const i = (y * W + x) * 4 + 3
            // Head fades out just past the mask edge; body is cut at the edge.
            headLayer[i] = Math.round(headLayer[i] * Math.min(1, Math.max(0, 1 - dist / head.feather)))
            if (dist < 0) bodyLayer[i] = 0
        }
    }

    await Promise.all([
        toPng(headLayer).toFile(path.join(outputDir, `${name}-head.png`)),
        toPng(bodyLayer).toFile(path.join(outputDir, `${name}-body.png`)),
    ])

    return {
        name,
        aspect: +(W / H).toFixed(4),
        hasHead: true,
        pivotX: +((cx / W) * 100).toFixed(2),
        pivotY: +((chin / H) * 100).toFixed(2),
    }
}

await rm(outputDir, { recursive: true, force: true })
await mkdir(outputDir, { recursive: true })
const names = (await readdir(inputDir))
    .filter((file) => file.endsWith(".png"))
    .map((file) => file.replace(/\.png$/, ""))
    .sort()
const results = []
for (const name of names) results.push(await prepare(name))
await writeFile(
    path.join(outputDir, "rig.ts"),
    `// Generated by scripts/make-loading-characters.mjs. Do not edit by hand.\nexport const characterRig = ${JSON.stringify(results, null, 4)} as const\n`,
)
console.log(results)

const previewIndex = process.argv.indexOf("--preview")
if (previewIndex > -1) {
    const tiles = await Promise.all(
        results.map(async (r) => {
            const layers = [{ input: path.join(outputDir, `${r.name}-body.png`) }]
            if (r.hasHead) layers.push({ input: path.join(outputDir, `${r.name}-head.png`) })
            const body = await sharp(layers[0].input).metadata()
            const base = await sharp({
                create: { width: body.width, height: body.height, channels: 4, background: "#0000" },
            })
                .composite(layers)
                .png()
                .toBuffer()
            return sharp(base)
                .resize({ width: 300, height: 480, fit: "contain", background: "#777" })
                .flatten({ background: "#777" })
                .png()
                .toBuffer()
        }),
    )
    await sharp({ create: { width: 300 * tiles.length, height: 480, channels: 3, background: "#777" } })
        .composite(tiles.map((input, i) => ({ input, left: i * 300, top: 0 })))
        .png()
        .toFile(process.argv[previewIndex + 1])
}
